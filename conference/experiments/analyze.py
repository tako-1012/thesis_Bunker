FIG = os.path.join(HERE, "..", "paper", "figures")

PLANNERS = ["A*", "Theta*", "A*-HC", "TA*", "TA*-S"]
# fixed entity -> colour mapping (validated categorical palette) + secondary encoding
COLOR = {"A*": "#eda100", "Theta*": "#e87ba4", "A*-HC": "#1baf7a",
         "TA*": "#2a78d6", "TA*-S": "#eb6834"}
