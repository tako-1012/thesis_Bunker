def macro_name(s):
    table = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
             "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    return "".join(table.get(c, c) for c in s if c.isalnum())


class Numbers:
    def __init__(self):
        self.items = {}

    def __setitem__(self, k, v):
        self.items[macro_name(k)] = v

    def write(self, path):
        with open(path, "w") as f:
            f.write("% AUTO-GENERATED by experiments/analyze.py -- do not edit\n")
            for k, v in sorted(self.items.items()):
                f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


def med_iqr(x, fmt="{:.1f}"):
    x = np.asarray(x, dtype=float)
    q1, q2, q3 = np.percentile(x, [25, 50, 75])
    return f"{fmt.format(q2)} [{fmt.format(q1)}, {fmt.format(q3)}]"


def holm(p):
    p = np.asarray(p)
    order = np.argsort(p)
    m = len(p)
    adj = np.empty(m)
    run = 0.0
    for rank, i in enumerate(order):
        run = max(run, (m - rank) * p[i])
        adj[i] = min(run, 1.0)
    return adj


def paired_test(a, b):
    """Wilcoxon signed-rank (two-sided) + matched-pairs rank-biserial r."""
    d = np.asarray(a, float) - np.asarray(b, float)
    nz = d[np.abs(d) > 1e-12]
    if len(nz) == 0:
        return 1.0, 0.0, 0.0
    p = wilcoxon(nz).pvalue
    ranks = pd.Series(np.abs(nz)).rank().to_numpy()
    r = (ranks[nz > 0].sum() - ranks[nz < 0].sum()) / ranks.sum()
    return float(p), float(r), float(np.median(d))


def fmt_p(p):
    if p < 1e-3:
        return "$<$0.001"
    return f"{p:.3f}"


def main():
    os.makedirs(GEN, exist_ok=True)
    os.makedirs(FIG, exist_ok=True)
    meta = json.load(open(os.path.join(RES, "meta.json")))
    df = pd.read_csv(os.path.join(RES, "test_results.csv"))
    val = pd.read_csv(os.path.join(RES, "val_sweep.csv"))
    N = Numbers()
    w_main = meta["w_main"]
    N["wMain"] = f"{w_main:g}"
    N["nTest"] = df[df.exp == "main"].groupby(["kind", "side_m", "seed"]).ngroups
    N["nVal"] = val.groupby(["kind", "side_m", "seed"]).ngroups
    N["nSeeds"] = len(meta["test_seeds"])
    N["nRedraw"] = int(df[(df.exp == "main") & (df.planner == "A*")].redraws.gt(0).sum())
    N["wallMin"] = f"{meta['wall_time_s'] / 60:.0f}"
    N["nCPU"] = meta["procs"]

    key = ["kind", "side_m", "seed"]
    main = df[df.exp == "main"].copy()
    ref = main[main.planner == "A*"].set_index(key)
    for col in ("length_xy", "energy_kj", "mean_cost", "climb"):
        main[col + "_rel"] = main.apply(
            lambda r: 100.0 * (r[col] / ref.loc[tuple(r[key]), col] - 1.0) if r.success else np.nan, axis=1)

    # ---------------- Table I: overall results ----------------
    rows = []
    for p in PLANNERS:
        d = main[main.planner == p]
        ok = d[d.success]
        succ = 100.0 * d.success.mean()
        N[f"succ{p}"] = f"{succ:.1f}"
        exposed = 100.0 * (ok.steep_len > 0).mean()
        N[f"exposed{p}"] = f"{exposed:.0f}"
        N[f"steepMean{p}"] = f"{ok.steep_len.mean():.1f}"
        N[f"lenRel{p}"] = f"{ok.length_xy_rel.median():.1f}"
        N[f"energyRel{p}"] = f"{ok.energy_kj_rel.median():.1f}"
        N[f"costRel{p}"] = f"{ok.mean_cost_rel.median():.1f}"
        N[f"climbRel{p}"] = f"{ok.climb_rel.median():.1f}"
        N[f"maxSlope{p}"] = f"{ok.max_slope.median():.1f}"
        N[f"pNineFiveSlope{p}"] = f"{ok.p95_slope.median():.1f}"
        N[f"time{p}"] = f"{ok.time.median():.3f}"
        N[f"timeMax{p}"] = f"{ok.time.max():.2f}"
        name = p.replace("*", "$^*$")
        rows.append(
            f"{name} & {succ:.0f} & {med_iqr(ok.length_xy_rel)} & {med_iqr(ok.energy_kj_rel)} & "
            f"{ok.max_slope.median():.1f} & {exposed:.0f} & {ok.steep_len.mean():.1f} & "
            f"{ok.mean_cost.median():.3f} & {ok.time.median():.3f} \\\\")
    with open(os.path.join(GEN, "table_main.tex"), "w") as f:
        f.write("% AUTO-GENERATED\n\\begin{table*}[t]\n\\centering\n"
                "\\caption{Results on the " + str(N.items["nTest"]) + " test scenarios. Length and energy "
                "are relative to A$^*$ on the same scenario, median [IQR]. Max.\\ slope and cost: medians. "
                "Exposed: share of paths that enter terrain steeper than $\\theta_{\\max}$; "
                "steep length: mean length driven on such terrain.}\n"
                "\\label{tab:main}\n\\setlength{\\tabcolsep}{4pt}\n"
                "\\begin{tabular}{lrrrrrrrr}\n\\toprule\n"
                "Planner & Succ.\\,[\\%] & $\\Delta$Length [\\%] & $\\Delta$Energy [\\%] & "
                "Max.\\ slope [$^\\circ$] & Exposed [\\%] & Steep len.\\ [m] & Cost $\\bar c$ & Time [s] \\\\\n"
                "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n")

    # ---------------- Table II: by terrain family ----------------
    rows = []
    for k in KINDS:
        cells = []
        for p in ("A*", "Theta*", "A*-HC", "TA*-S"):
            ok = main[(main.planner == p) & (main.kind == k) & main.success]
            cells.append(f"{ok.mean_cost.median():.3f}")
        for p in ("A*", "Theta*"):
            ok = main[(main.planner == p) & (main.kind == k) & main.success]
            cells.append(f"{100 * (ok.steep_len > 0).mean():.0f}")
        ok = main[(main.planner == "TA*-S") & (main.kind == k) & main.success]
        cells.append(f"{ok.length_xy_rel.median():.1f}")
        cells.append(f"{ok.energy_kj_rel.median():.1f}")
        N[f"costRelTAS{k}"] = f"{ok.mean_cost_rel.median():.1f}"
        N[f"lenRelTAS{k}"] = f"{ok.length_xy_rel.median():.1f}"
        N[f"energyRelTAS{k}"] = f"{ok.energy_kj_rel.median():.1f}"
        for p in ("A*", "Theta*"):
            okp = main[(main.planner == p) & (main.kind == k) & main.success]
            N[f"exposed{p}{k}"] = f"{100 * (okp.steep_len > 0).mean():.0f}"
        rows.append(f"{k} & " + " & ".join(cells) + " \\\\")
    with open(os.path.join(GEN, "table_kind.tex"), "w") as f:
        f.write("% AUTO-GENERATED\n\\begin{table}[t]\n\\centering\n"
                "\\caption{Per terrain family (medians). $\\bar c$: mean traversability cost along the path; "
                "Exposed: share of paths entering slopes $>\\theta_{\\max}$; $\\Delta$: TA$^*$-S relative to A$^*$.}\n"
                "\\label{tab:kind}\n\\setlength{\\tabcolsep}{2.5pt}\n"
                "\\begin{tabular}{lrrrrrrrr}\n\\toprule\n"
                " & \\multicolumn{4}{c}{$\\bar c$} & \\multicolumn{2}{c}{Exposed [\\%]} & \\multicolumn{2}{c}{TA$^*$-S $\\Delta$ [\\%]}\\\\\n"
                "\\cmidrule(lr){2-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\n"
                "Terrain & A$^*$ & Th$^*$ & HC & TA$^*$-S & A$^*$ & Th$^*$ & Len. & Energy \\\\\n"
                "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")

    # ---------------- Table III: paired tests ----------------
    comps = [("TA*-S", "A*"), ("TA*-S", "Theta*"), ("TA*-S", "A*-HC"), ("TA*-S", "TA*")]
    metrics = [("mean_cost", "cost $\\bar c$", "{:+.3f}"), ("p95_slope", "95th-pct.\\ slope [$^\\circ$]", "{:+.2f}"),
               ("climb", "climb [m]", "{:+.2f}"), ("energy_kj", "energy [kJ]", "{:+.2f}"),
               ("length_xy", "length [m]", "{:+.2f}")]
    tests = []
    piv = main[main.success].pivot_table(index=key, columns="planner", values=[m for m, _, _ in metrics])
    for a, b in comps:
        for m, label, fmt in metrics:
            sub = piv[m][[a, b]].dropna()
            p, r, dmed = paired_test(sub[a], sub[b])
            tests.append({"a": a, "b": b, "metric": m, "label": label, "p": p, "r": r,
                          "d": fmt.format(dmed), "n": len(sub), "dval": dmed})
    adj = holm([t["p"] for t in tests])
    for t, pa in zip(tests, adj):
        t["p_holm"] = pa
    lines, last = [], None
    for t in tests:
        pair = f"{t['a']} vs {t['b']}".replace("*", "$^*$")
        if last is not None and pair != last:
            lines.append("\\midrule")
        lines.append(f"{pair if pair != last else ''} & {t['label']} & {t['d']} & {t['r']:+.2f} & {fmt_p(t['p_holm'])} \\\\")
        last = pair
        N[f"r{t['a']}{t['b']}{t['metric']}"] = f"{t['r']:+.2f}"
        N[f"p{t['a']}{t['b']}{t['metric']}"] = fmt_p(t["p_holm"])
        N[f"d{t['a']}{t['b']}{t['metric']}"] = t["d"]
    N["nTests"] = len(tests)
    with open(os.path.join(GEN, "table_tests.tex"), "w") as f:
        f.write("% AUTO-GENERATED\n\\begin{table}[t]\n\\centering\n"
                "\\caption{Paired two-sided Wilcoxon signed-rank tests over the test scenarios "
                f"(n={tests[0]['n']}). $\\tilde d$: median paired difference (first minus second); "
                "$r$: matched-pairs rank-biserial correlation; $p$: Holm-corrected over all "
                f"{len(tests)} tests.}}\n\\label{{tab:tests}}\n\\setlength{{\\tabcolsep}}{{3pt}}\n"
                "\\begin{tabular}{llrrr}\n\\toprule\nComparison & Metric & $\\tilde d$ & $r$ & $p$ \\\\\n\\midrule\n"
                + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    pd.DataFrame(tests).to_csv(os.path.join(RES, "paired_tests.csv"), index=False)

    # ---------------- Fig: example paths ----------------
    ex = np.load(os.path.join(RES, "examples.npy"), allow_pickle=True).item()
    fig, axs = plt.subplots(1, 4, figsize=(7.16, 2.05))
    ls = LightSource(azdeg=315, altdeg=45)
    for ax, k in zip(axs, KINDS):
        e = ex[k]
        n = e["elev"].shape[0]
        ext = [0, n * 0.5, 0, n * 0.5]
        shade = ls.hillshade(e["elev"].T, vert_exag=2, dx=0.5, dy=0.5)
        ax.imshow(shade, cmap="gray", origin="lower", extent=ext, vmin=0, vmax=1.2)
        ax.imshow(np.ma.masked_where(~e["lethal"].T, e["lethal"].T), cmap="Greys", alpha=0.55,
                  origin="lower", extent=ext, vmin=0, vmax=1.3)
        for p in ("A*", "Theta*", "A*-HC", "TA*-S"):
            P = e["paths"][p]
            if P is None:
                continue
            xy = (P + 0.5) * 0.5
            ax.plot(xy[:, 0], xy[:, 1], color="white", lw=2.4, solid_capstyle="round")
            ax.plot(xy[:, 0], xy[:, 1], color=COLOR[p], lw=1.2, label=p, solid_capstyle="round")
        for c, mk in ((e["start"], "o"), (e["goal"], "*")):
            ax.plot((c[0] + 0.5) * 0.5, (c[1] + 0.5) * 0.5, mk, color="white", mec=INK, ms=6, mew=0.8)
        ax.set_title(k, color=INK)
        ax.set_xticks([0, 50, 100])
        ax.set_yticks([0, 50, 100])
        ax.grid(False)
        ax.set_xlabel("x [m]")
    axs[0].set_ylabel("y [m]")
    h, l = axs[0].get_legend_handles_labels()
    fig.legend(h, l, loc="upper center", ncol=4, frameon=False, bbox_to_anchor=(0.5, 1.04))
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(os.path.join(FIG, "examples.pdf"))
    fig.savefig(os.path.join(FIG, "examples.png"))
    plt.close(fig)

    # ---------------- Fig: weight sweep (trade-off) ----------------
    sw = df[(df.exp == "sweep") & df.success].copy()
    sw = sw.join(ref[["length_xy", "energy_kj", "mean_cost"]].rename(columns=lambda c: c + "_A"), on=key)
    sw["len_rel"] = 100 * (sw.length_xy / sw.length_xy_A - 1)
    sw["energy_rel"] = 100 * (sw.energy_kj / sw.energy_kj_A - 1)
    agg = sw.groupby(["planner", "w"]).agg(len_rel=("len_rel", "median"), cost=("mean_cost", "median"),
                                          energy_rel=("energy_rel", "median"), time=("time", "median")).reset_index()
    agg.to_csv(os.path.join(RES, "sweep_summary.csv"), index=False)
    fig, axs = plt.subplots(1, 2, figsize=(COL_W, 1.75))
    for p in ("TA*", "TA*-S"):
        a = agg[agg.planner == p].sort_values("w")
        axs[0].plot(a.len_rel, a.cost, marker=MARK[p], ms=3.5, color=COLOR[p], label=p)
        axs[1].plot(a.w, a.energy_rel, marker=MARK[p], ms=3.5, color=COLOR[p], label=p)
        if p == "TA*-S":
            for _, r_ in a.iterrows():
                if r_.w in (0.0, 2.0, 8.0, 32.0):
                    axs[0].annotate(f"w={r_.w:g}", (r_.len_rel, r_.cost), fontsize=5.5, color=MUTED,
                                    xytext=(3, 2), textcoords="offset points")
    for p in ("A*", "Theta*"):
        ok = main[(main.planner == p) & main.success]
        axs[0].plot(ok.length_xy_rel.median(), ok.mean_cost.median(), MARK[p], color=COLOR[p], ms=4, label=p)
    axs[0].set_xlabel(r"$\Delta$length vs. A$^*$ [%]")
    axs[0].set_ylabel(r"median cost $\bar c$")
    axs[1].axhline(0, color=MUTED, lw=0.6)
    axs[1].set_xscale("symlog", linthresh=0.5)
    axs[1].set_xticks([0, 1, 4, 16])
    axs[1].set_xticklabels(["0", "1", "4", "16"])
    axs[1].axvline(w_main, color=MUTED, lw=0.6, ls="--")
    axs[1].set_xlabel("terrain weight $w$")
    axs[1].set_ylabel(r"$\Delta$energy vs. A$^*$ [%]")
    axs[0].legend(frameon=False, loc="upper right")
    fig.tight_layout(pad=0.3)
    fig.savefig(os.path.join(FIG, "sweep.pdf"))
    fig.savefig(os.path.join(FIG, "sweep.png"))
    plt.close(fig)
    for _, r_ in agg[agg.planner == "TA*-S"].iterrows():
        tag = f"{r_.w:g}".replace(".", "p")
        N[f"sweepLen{tag}"] = f"{r_.len_rel:.1f}"
        N[f"sweepCost{tag}"] = f"{r_.cost:.3f}"
        N[f"sweepEnergy{tag}"] = f"{r_.energy_rel:.1f}"
    vo = meta["val_overhead"]
    N["valOverheadMain"] = f"{100 * vo[str(w_main) if str(w_main) in vo else f'{w_main}']:.1f}"

    # ---------------- Fig: computation time vs. map size ----------------
    fig, ax = plt.subplots(figsize=(COL_W * 0.5, 1.75))
    for p in PLANNERS:
        d = main[(main.planner == p) & main.success].groupby("side_m").time.median()
        ax.plot(d.index, d.values, marker=MARK[p], ms=3.5, color=COLOR[p], label=p)
        for s, v in d.items():
            N[f"time{p}{s}"] = f"{v:.3f}"
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xticks([50, 100, 200])
    ax.set_xticklabels(["50", "100", "200"])
    ax.minorticks_off()
    ax.set_xlabel("map side [m]")
    ax.set_ylabel("median time [s]")
    ax.legend(frameon=False, fontsize=5.5, loc="upper left")
    fig.tight_layout(pad=0.3)
    fig.savefig(os.path.join(FIG, "time.pdf"))
    fig.savefig(os.path.join(FIG, "time.png"))
    plt.close(fig)

    # ---------------- Fig: robustness to elevation noise ----------------
    nz = df[df.exp == "noise"].copy()
    fig, axs = plt.subplots(1, 2, figsize=(COL_W, 1.6))
    for p in ("A*-HC", "TA*"):
        g = nz.groupby("noise")
        succ = g.apply(lambda d: 100 * d[d.planner == p].success.mean())
        ok = nz[(nz.planner == p) & nz.success]
        steep = ok.groupby("noise").steep_len.mean()
        # sigma = 0 point from the main experiment
        ok0 = main[(main.planner == p) & main.success]
        xs = [0.0] + list(steep.index)
        axs[0].plot(xs, [ok0.steep_len.mean()] + list(steep.values), marker=MARK[p], ms=3.5,
                    color=COLOR[p], label=p)
        axs[1].plot(xs, [100 * main[main.planner == p].success.mean()] + list(succ.values),
                    marker=MARK[p], ms=3.5, color=COLOR[p], label=p)
        for s in steep.index:
            tag = f"{s:g}".replace(".", "p")
            N[f"noiseSteep{p}{tag}"] = f"{steep[s]:.2f}"
            N[f"noiseSucc{p}{tag}"] = f"{succ[s]:.1f}"
            N[f"noiseCost{p}{tag}"] = f"{ok[ok.noise == s].mean_cost.median():.3f}"
    axs[0].set_xlabel(r"elevation noise $\sigma_z$ [m]")
    axs[0].set_ylabel("mean steep length [m]")
    axs[1].set_xlabel(r"elevation noise $\sigma_z$ [m]")
    axs[1].set_ylabel("success [%]")
    axs[1].legend(frameon=False, loc="lower left")
    fig.tight_layout(pad=0.3)
    fig.savefig(os.path.join(FIG, "noise.pdf"))
    fig.savefig(os.path.join(FIG, "noise.png"))
    plt.close(fig)

    # ---------------- Ablation (alpha) ----------------
    ab = df[(df.exp == "ablation") & df.success]
    rows = []
    for a, d in ab.groupby("alpha"):
        rows.append(f"{a:.2f} & {d.p95_slope.median():.1f} & {1000 * d.p95_rough.median():.1f} & "
                    f"{d.climb.median():.2f} & {d.length_xy.median():.1f} \\\\")
        tag = f"{a:g}".replace(".", "p")
        N[f"abSlope{tag}"] = f"{d.p95_slope.median():.1f}"
        N[f"abRough{tag}"] = f"{1000 * d.p95_rough.median():.1f}"
    with open(os.path.join(GEN, "table_ablation.tex"), "w") as f:
        f.write("% AUTO-GENERATED\n\\begin{table}[t]\n\\centering\n"
                "\\caption{Ablation of the slope/roughness weighting ($\\beta = 1-\\alpha$) for TA$^*$ "
                f"($w={w_main:g}$), medians over the test scenarios, evaluated with the default cost map.}}\n"
                "\\label{tab:ablation}\n\\setlength{\\tabcolsep}{4pt}\n"
                "\\begin{tabular}{rrrrr}\n\\toprule\n"
                "$\\alpha$ & 95th-pct.\\ slope [$^\\circ$] & 95th-pct.\\ rough.\\ [mm] & climb [m] & length [m] \\\\\n"
                "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")

    N.write(os.path.join(GEN, "numbers.tex"))
    print("wrote", len(N.items), "macros; tables and figures in paper/")


if __name__ == "__main__":
    main()
