#!/usr/bin/env python3
"""Analyse E7 (roll-aware extension).

Outputs paper/generated/table_roll.tex, paper/generated/numbers_roll.tex and
results/roll_tests.csv.

Usage (from conference/):  python3 experiments/analyze_roll.py
"""
import os

import numpy as np
import pandas as pd

from analyze import GEN, RES, Numbers, holm, paired_test, fmt_p  # noqa: E402

KEY = ["kind", "side_m", "seed"]
LIMITS = (10.0, 15.0, 20.0, 25.0)
MAIN = 20.0
ROWS = ("A*", "Theta*", "A*-HC", "TA*-S", "TA*-R", "TA*-S-R")


def main():
    N = Numbers()
    d = pd.read_csv(os.path.join(RES, "roll_results.csv"))
    d["success"] = d.success.astype(bool)
    d["roll_len"] = d.roll_frac * d.length_xy
    N["rlMain"] = f"{MAIN:g}"
    N["rlNScen"] = d.groupby(KEY).ngroups

    out = {}
    for lim in LIMITS:
        x = d[d.roll_limit == lim]
        ref = x[x.planner == "A*"].set_index(KEY)
        for p in ROWS:
            g = x[x.planner == p]
            ok = g[g.success].set_index(KEY)
            rel = lambda c: float((100 * (ok[c] / ref.loc[ok.index, c] - 1)).median())  # noqa: E731
            out[(p, lim)] = {
                "succ": 100 * g.success.mean(), "nfail": int((~g.success).sum()),
                "exposed": 100 * (ok.roll_frac > 0).mean(), "roll_len": ok.roll_len.mean(),
                "roll_len_max": ok.roll_len.max(), "max_roll": ok.max_roll.median(),
                "max_roll_max": ok.max_roll.max(), "p95_roll": ok.p95_roll.median(),
                "dL": rel("length_xy"), "dE": rel("energy_kj"), "time": ok.time.median()}
            tag = p.replace("*", "").replace("-", "")
            lt = {10.0: "Ten", 15.0: "Fifteen", 20.0: "Twenty", 25.0: "TwentyFive"}[lim]
            o = out[(p, lim)]
            N[f"rl{tag}Exposed{lt}"] = f"{o['exposed']:.0f}"
            N[f"rl{tag}RollLen{lt}"] = f"{o['roll_len']:.2f}"
            N[f"rl{tag}Succ{lt}"] = f"{o['succ']:.1f}"
            N[f"rl{tag}Fail{lt}"] = o["nfail"]
            N[f"rl{tag}MaxRoll{lt}"] = f"{o['max_roll']:.1f}"
            N[f"rl{tag}MaxRollMax{lt}"] = f"{o['max_roll_max']:.1f}"
            N[f"rl{tag}RollLenMax{lt}"] = f"{o['roll_len_max']:.2f}"
            N[f"rl{tag}DL{lt}"] = f"{o['dL']:.1f}"
            N[f"rl{tag}DE{lt}"] = f"{o['dE']:.1f}"
            N[f"rl{tag}Time{lt}"] = f"{o['time']:.3f}"
            if lim == MAIN:
                for fld, val in (("Exposed", f"{o['exposed']:.0f}"), ("RollLen", f"{o['roll_len']:.2f}"),
                                 ("Fail", o["nfail"]), ("MaxRoll", f"{o['max_roll']:.1f}"),
                                 ("DL", f"{o['dL']:.1f}"), ("DE", f"{o['dE']:.1f}")):
                    N[f"rl{tag}{fld}Main"] = val

    # paired tests at the main roll limit: TA*-S-R vs TA*-S
    x = d[(d.roll_limit == MAIN) & d.success]
    piv = x.pivot_table(index=KEY, columns="planner",
                        values=["max_roll", "p95_roll", "roll_len", "length_xy", "energy_kj"])
    tests = []
    for m in ("max_roll", "p95_roll", "roll_len", "length_xy", "energy_kj"):
        sub = piv[m][["TA*-S-R", "TA*-S"]].dropna()
        p, r, dm = paired_test(sub["TA*-S-R"], sub["TA*-S"])
        tests.append((m, p, r, dm, len(sub)))
    adj = holm([t[1] for t in tests])
    names = {"max_roll": "MaxRoll", "p95_roll": "PRoll", "roll_len": "RollLen",
             "length_xy": "Len", "energy_kj": "Energy"}
    for (m, p, r, dm, n), pa in zip(tests, adj):
        N[f"rlTest{names[m]}P"] = fmt_p(pa)
        N[f"rlTest{names[m]}Pexpr"] = "$p<0.001$" if pa < 1e-3 else f"$p={pa:.3f}$"
        N[f"rlTest{names[m]}R"] = f"{r:+.2f}"
        N[f"rlTest{names[m]}D"] = f"{dm:+.2f}"
    pd.DataFrame([dict(metric=m, p=p, p_holm=pa, r=r, median_diff=dm, n=n)
                  for (m, p, r, dm, n), pa in zip(tests, adj)]).to_csv(
        os.path.join(RES, "roll_tests.csv"), index=False)

    # table
    lines = []
    for p in ("A*", "Theta*", "A*-HC", "TA*-S", "TA*-S-R"):
        o = out[(p, MAIN)]
        exp = " & ".join(f"{out[(p, lim)]['exposed']:.0f}" for lim in LIMITS)
        lines.append(f"{p.replace('*', '$^*$')} & {exp} & {o['roll_len']:.2f} & {o['max_roll']:.1f} & "
                     f"{o['dL']:.1f} & {o['dE']:.1f} \\\\")
    with open(os.path.join(GEN, "table_roll.tex"), "w") as f:
        f.write("% AUTO-GENERATED by analyze_roll.py\n\\begin{table}[t]\n\\centering\n"
                "\\caption{Roll exposure on the test scenarios. Exposed: share of paths with roll above "
                "the roll limit $\\phi_{\\max}$ anywhere; len.: mean distance above the limit; max: maximum "
                f"roll; max, $\\Delta L$, $\\Delta E$ (relative to A$^*$): medians; all at $\\phi_{{\\max}}={MAIN:g}^\\circ$ "
                "unless stated. TA$^*$-S-R uses the roll limit it is evaluated with.}\n"
                "\\label{tab:roll}\n\\setlength{\\tabcolsep}{1.3pt}\n"
                "\\begin{tabular}{lrrrrrrrr}\n\\toprule\n"
                " & \\multicolumn{4}{c}{Exposed [\\%] at $\\phi_{\\max}$} & & & & \\\\\n"
                "\\cmidrule(lr){2-5}\n"
                "Planner & 10$^\\circ$ & 15$^\\circ$ & 20$^\\circ$ & 25$^\\circ$ & len.\\ [m] & max [$^\\circ$] & "
                "$\\Delta L$ [\\%] & $\\Delta E$ [\\%] \\\\\n\\midrule\n"
                + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    N.write(os.path.join(GEN, "numbers_roll.tex"))
    print(open(os.path.join(GEN, "table_roll.tex")).read())
    print(pd.read_csv(os.path.join(RES, "roll_tests.csv")))


if __name__ == "__main__":
    main()
